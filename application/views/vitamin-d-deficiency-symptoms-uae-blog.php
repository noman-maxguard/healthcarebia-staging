                            <h3>Low immunity</h3>
                            <p>Vitamin D has a major role in the regulation of the immune system. It assists the body in the production of anti-infective proteins that are needed in the prevention of colds and flu. Lack can cause you to be more susceptible to frequent infections, slow healing and inflammation. This is especially vulnerable to residents who spend most of their time indoors, be it in offices, cars, or air-conditioned spaces.</p>
                        </li>
