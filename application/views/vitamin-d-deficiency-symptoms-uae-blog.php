                        </li>
                        <li>
                            <h3>Low mood and Irritability</h3>
                            <p>The lack can be reflected in mood swings, irritability, or lack of motivation, which are not very obvious. Vitamin D aids in the stabilization of serotonin and dopamine, the neurotransmitters that determine our mood. Indoor-oriented people may attribute such changes to stress or fatigue, but lack of vitamin D may be a significant cause.</p>
                        </li>
